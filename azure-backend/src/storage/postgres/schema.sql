-- Run as a deployment administrator, not the application's runtime identity.
BEGIN;
CREATE SCHEMA IF NOT EXISTS deskpilot;
CREATE SEQUENCE IF NOT EXISTS deskpilot.record_version AS bigint;
CREATE TABLE IF NOT EXISTS deskpilot.records (
  workspace_id varchar(64) NOT NULL,
  kind varchar(32) NOT NULL,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  parent_id bigint NOT NULL DEFAULT 0,
  owner_id varchar(64) NOT NULL DEFAULT '',
  document jsonb NOT NULL CHECK (jsonb_typeof(document)='object'),
  version bigint NOT NULL DEFAULT nextval('deskpilot.record_version'),
  requester_email text GENERATED ALWAYS AS (lower(document #>> '{Requester,Email}')) STORED,
  creator_email text GENERATED ALWAYS AS (lower(document #>> '{CreatedBy,Email}')) STORED,
  assigned_email text GENERATED ALWAYS AS (lower(document #>> '{AssignedTo,Email}')) STORED,
  department text GENERATED ALWAYS AS (document ->> 'Department') STORED,
  PRIMARY KEY (workspace_id,kind,id),
  CHECK (id > 0 AND id <= 9007199254740991)
);
CREATE OR REPLACE FUNCTION deskpilot.advance_record_version() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.version := nextval('deskpilot.record_version');
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS record_version_update ON deskpilot.records;
CREATE TRIGGER record_version_update BEFORE UPDATE ON deskpilot.records
  FOR EACH ROW EXECUTE FUNCTION deskpilot.advance_record_version();
CREATE INDEX IF NOT EXISTS records_parent ON deskpilot.records(workspace_id,kind,parent_id,id DESC);
CREATE INDEX IF NOT EXISTS records_owner ON deskpilot.records(workspace_id,kind,owner_id,id DESC);
CREATE INDEX IF NOT EXISTS records_requester ON deskpilot.records(workspace_id,kind,requester_email,id DESC);
CREATE INDEX IF NOT EXISTS records_creator ON deskpilot.records(workspace_id,kind,creator_email,id DESC);
CREATE INDEX IF NOT EXISTS records_assignee ON deskpilot.records(workspace_id,kind,assigned_email,id DESC);
CREATE INDEX IF NOT EXISTS records_department ON deskpilot.records(workspace_id,kind,department,id DESC);
CREATE UNIQUE INDEX IF NOT EXISTS records_view ON deskpilot.records(workspace_id,parent_id,owner_id) WHERE kind='view';
CREATE UNIQUE INDEX IF NOT EXISTS records_rotation ON deskpilot.records(workspace_id,parent_id) WHERE kind='rotation';
COMMIT;
